from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
import copy,json,sys,tempfile
from pathlib import Path
import numpy as np
sys.path.insert(0,str(ROOT/'tests'))
import validate as v
base=json.load(open(ROOT/'authoring/evidence/reference-output.json'));checks=[]
def bad(name,change,fn=v.schema):
    a=copy.deepcopy(base);change(a)
    try:fn(a)
    except (AssertionError,ValueError,TypeError,KeyError,IndexError,OverflowError):checks.append({'name':name,'rejected':True})
    else:checks.append({'name':name,'rejected':False})
bad('missing required top-level result',lambda a:a.pop('queries'))
bad('extra top-level key',lambda a:a.update(extra=1))
bad('boolean mechanism',lambda a:a.update(mechanism=True))
bad('unsupported mechanism',lambda a:a.update(mechanism=3))
bad('numeric string',lambda a:a['parameters'].update(alpha='0.43'))
bad('boolean parameter',lambda a:a['parameters'].update(alpha=True))
bad('nonfinite parameter',lambda a:a['parameters'].update(alpha=float('nan')))
bad('out of bound parameter',lambda a:a['parameters'].update(alpha=1.2))
bad('missing measurement',lambda a:a['measurements'].pop())
bad('wrong measurement ID',lambda a:a['measurements'][0].update(id='unknown'))
bad('wrong spectrum shape',lambda a:a['measurements'][0]['impedance_ohm_cm2'].pop())
bad('boolean spectrum value',lambda a:a['measurements'][0]['impedance_ohm_cm2'][0].__setitem__(0,True))
bad('wrong state dimension',lambda a:a['measurements'][0]['state'].append(1))
bad('missing query',lambda a:a['queries'].pop())
bad('wrong orbit shape',lambda a:a['queries'][0]['orbits'][0]['states'].pop())
bad('negative period',lambda a:a['queries'][0]['orbits'][0].update(period_s=-1))
bad('orbit outside physical domain',lambda a:a['queries'][0]['orbits'][0]['states'][2].__setitem__(1,-.1))
bad('missing Floquet multiplier',lambda a:a['queries'][0]['orbits'][0]['nontrivial_floquet_multipliers'].pop())
bad('forged likelihood',lambda a:a.update(fit_chi_square=0),v.measurements)
bad('wrong turnover mechanism',lambda a:a.update(mechanism=1),v.measurements)
bad('negated imaginary impedance',lambda a:a['measurements'][0]['impedance_ohm_cm2'][0].__setitem__(1,-a['measurements'][0]['impedance_ohm_cm2'][0][1]),v.measurements)
bad('omitted fold',lambda a:a['folds']['standard'].pop(),v.equilibrium_geometry)
bad('omitted unstable equilibrium',lambda a:a['queries'][0]['equilibria'].pop(0),v.equilibrium_geometry)
bad('angular frequency reported as Hz',lambda a:a['queries'][0]['hopf_points'][0].update(frequency_Hz=a['queries'][0]['hopf_points'][0]['frequency_Hz']*2*np.pi),v.local_bifurcations)
bad('wrong Lyapunov normalization',lambda a:a['queries'][0]['hopf_points'][0].update(first_lyapunov=a['queries'][0]['hopf_points'][0]['first_lyapunov']*2),v.local_bifurcations)
bad('additional instead of total capacitance',lambda a:a['queries'][0]['hopf_points'][0].update(total_capacitance_F_cm2=a['queries'][0]['hopf_points'][0]['total_capacitance_F_cm2']-a['parameters']['Cdl_F_cm2']),v.local_bifurcations)
bad('wrong crossing direction',lambda a:a['queries'][0]['hopf_points'][0].update(eigenvalue_slope_per_F_cm2_s=-a['queries'][0]['hopf_points'][0]['eigenvalue_slope_per_F_cm2_s']),v.local_bifurcations)
bad('trivial unit multipliers substituted',lambda a:a['queries'][0]['orbits'][0].update(nontrivial_floquet_multipliers=[1.,1.]),v.nonlinear_orbits)
bad('nonlinear orbit period replaced by Hopf period',lambda a:a['queries'][0]['orbits'][0].update(period_s=1/a['queries'][0]['hopf_points'][0]['frequency_Hz']),v.nonlinear_orbits)
bad('double traversal counted as a period',lambda a:a['queries'][0]['orbits'][0].update(period_s=2*a['queries'][0]['orbits'][0]['period_s'],states=(a['queries'][0]['orbits'][0]['states'][::2])*2,nontrivial_floquet_multipliers=[x*x for x in a['queries'][0]['orbits'][0]['nontrivial_floquet_multipliers']]),v.nonlinear_orbits)
bad('equilibrium substituted for orbit',lambda a:a['queries'][0]['orbits'][0].update(states=[a['queries'][0]['hopf_points'][0]['state']]*64),v.nonlinear_orbits)
bad('single orbit sample corrupted',lambda a:a['queries'][0]['orbits'][0]['states'][32].__setitem__(2,.5),v.nonlinear_orbits)
bad('criticality change at wrong command',lambda a:a['criticality_change'].update(command_V=-.274),v.criticality_change)
bad('wrong criticality-curve slope',lambda a:a['criticality_change'].update(lyapunov_slope_per_V=0),v.criticality_change)
bad('cycle fold replaced by regular cycle',lambda a:a['cycle_bistability'].update(fold_orbit=copy.deepcopy(a['cycle_bistability']['unstable_orbit'])),v.cycle_bistability)
bad('stable cycle duplicated as unstable',lambda a:a['cycle_bistability'].update(unstable_orbit=copy.deepcopy(a['cycle_bistability']['stable_orbit'])),v.cycle_bistability)
bad('stable and unstable cycles swapped',lambda a:a['cycle_bistability'].update(unstable_orbit=copy.deepcopy(a['cycle_bistability']['stable_orbit']),stable_orbit=copy.deepcopy(a['cycle_bistability']['unstable_orbit'])),v.cycle_bistability)
bad('wrong coexistence midpoint',lambda a:a['cycle_bistability'].update(coexistence_capacitance_F_cm2=a['cycle_bistability']['coexistence_capacitance_F_cm2']+5e-8),v.cycle_bistability)
bad('incorrect fold multiplier',lambda a:a['cycle_bistability']['fold_orbit'].update(nontrivial_floquet_multipliers=[.026,.9]),v.cycle_bistability)
bad('constant substrate on stable cycle',lambda a:[row.__setitem__(2,a['cycle_bistability']['equilibrium'][2]) for row in a['cycle_bistability']['stable_orbit']['states']],v.cycle_bistability)
with tempfile.TemporaryDirectory() as td:
    path=Path(td)/'output.json'
    for name,text in [('duplicate key','{"x":1,"x":2}'),('NaN token','{"x":NaN}'),('truncated JSON','{"x":'),('too large',' '*1000001)]:
        path.write_text(text)
        try:v.read(path)
        except (ValueError,AssertionError):checks.append({'name':name,'rejected':True})
        else:checks.append({'name':name,'rejected':False})
    target=Path(td)/'target.json';target.write_text('{}');path.unlink();path.symlink_to(target)
    try:v.read(path)
    except AssertionError:checks.append({'name':'symlink artifact','rejected':True})
    else:checks.append({'name':'symlink artifact','rejected':False})
json.dump(checks,open(ROOT/'authoring/evidence/regressions.json','w'),indent=2)
print('Rejected',sum(r['rejected'] for r in checks),'of',len(checks))
assert all(r['rejected'] for r in checks)
